class HealthCheckUser(HttpUser):
    """
    Simulates monitoring systems checking health and metrics.
    
    INCUBATION: No monitoring load testing
    PRODUCTION: Realistic health check load pattern
    
    Configuration:
    - wait_time: 5-15 seconds between requests
    - weight: 1 (less common than WebFormUser)
    
    Tasks:
    - check_health: GET /health
    - check_metrics: GET /metrics/channels
    """
    
    # Wait 5-15 seconds between tasks
    wait_time = between(5, 15)
    
    # Weight: 1x (less common than WebFormUser)
    weight = 1
    
    @task(2)
    def check_health(self):
        """
        Check the health endpoint.
        
        INCUBATION: No health endpoint
        PRODUCTION: Health check monitoring under load
        
        Weight: 2 (2x more common than check_metrics)
        """
        self.client.get(
            "/health",
            name="/health"
        )
    
    @task(1)
    def check_metrics(self):
        """
        Check the metrics endpoint.
        
        INCUBATION: No metrics endpoint
        PRODUCTION: Metrics monitoring under load
        
        Weight: 1
        """
        self.client.get(
            "/metrics/channels",
            name="/metrics/channels"
        )


# ============================================================================
# LOCUST EVENT HOOKS
# ============================================================================

@events.test_start.add_listener
def on_test_start(environment, **kwargs):
    """
    Called when load test starts.
    
    Args:
        environment: Locust environment
    """
    print("=" * 70)
    print("TechCorp FTE Load Test Starting")
    print("=" * 70)
    print(f"Target Host: {environment.host}")
    print(f"User Classes: WebFormUser (weight=3), HealthCheckUser (weight=1)")
    print("=" * 70)


@events.test_stop.add_listener
def on_test_stop(environment, **kwargs):
    """
    Called when load test stops.
    
    Args:
        environment: Locust environment
    """
    print()
    print("=" * 70)
    print("TechCorp FTE Load Test Complete")
    print("=" * 70)
    
    # Print summary statistics
    stats = environment.stats
    print(f"Total Requests: {stats.total.num_requests}")
    print(f"Total Failures: {stats.total.num_failures}")
    print(f"Failure Rate: {stats.total.fail_ratio * 100:.2f}%")
    print(f"Average Response Time: {stats.total.avg_response_time:.2f}ms")
    print(f"Requests/sec: {stats.total.current_rps:.2f}")
    print("=" * 70)


@events.request.add_listener
def on_request(request_type, name, response_time, response_length, exception, **kwargs):
    """
    Called on each request for custom logging.
    
    Args:
        request_type: HTTP method
        name: Endpoint name
        response_time: Response time in ms
        response_length: Response size in bytes
        exception: Exception if any
    """
    # Log slow requests
    if response_time > 1000:
        print(f"WARNING: Slow request to {name}: {response_time:.0f}ms")


