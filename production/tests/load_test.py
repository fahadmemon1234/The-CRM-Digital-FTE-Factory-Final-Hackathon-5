import random
import string
from locust import HttpUser, task, between, events


# ============================================================================
# HELPER FUNCTIONS
# ============================================================================

def random_string(length: int = 10) -> str:
    """Generate a random string of specified length."""
    return ''.join(random.choices(string.ascii_letters + string.digits, k=length))


def random_email() -> str:
    """Generate a random email address."""
    domains = ["example.com", "test.com", "loadtest.local", "user.io"]
    return f"{random_string(8)}@{random.choice(domains)}"


def random_name() -> str:
    """Generate a random name."""
    first_names = ["John", "Jane", "Bob", "Alice", "Charlie", "Diana", "Eve", "Frank"]
    last_names = ["Smith", "Johnson", "Williams", "Brown", "Jones", "Garcia", "Miller"]
    return f"{random.choice(first_names)} {random.choice(last_names)}"


# ============================================================================
# USER CLASS 1: Web Form User
# ============================================================================

class WebFormUser(HttpUser):
    """
    Simulates users submitting support forms via web form.
    
    INCUBATION: No load testing
    PRODUCTION: Realistic web form submission load
    
    Configuration:
    - wait_time: 2-10 seconds between requests
    - weight: 3 (3x more likely to be selected than HealthCheckUser)
    
    Tasks:
    - submit_support_form: POST /support/submit with random data
    """
    
    # Wait 2-10 seconds between tasks
    wait_time = between(2, 10)
    
    # Weight: 3x more common than HealthCheckUser
    weight = 3
    
    # Fixed message for load testing
    LOAD_TEST_MESSAGE = (
        "I am experiencing issues with the system during load testing. "
        "This is an automated message generated by Locust for performance testing purposes. "
        "Please investigate the reported issue and provide assistance."
    )
    
    # Valid categories
    CATEGORIES = ["general", "technical", "billing", "feedback", "bug_report"]
    
    @task
    def submit_support_form(self):
        """
        Submit a support form with random data.
        
        INCUBATION: No form submission testing
        PRODUCTION: Realistic load test with randomized data
        
        Generates:
        - Random name (1-10000 characters for stress testing)
        - Random email address
        - Random subject (1-100 characters)
        - Random category from valid list
        - Fixed load test message
        """
        # Generate random name (varying length for stress testing)
        name_length = random.randint(1, 10000)
        name = random_string(name_length) if name_length <= 100 else random_name()
        
        # Generate random email
        email = random_email()
        
        # Generate random subject (1-100 characters)
        subject_length = random.randint(1, 100)
        subject = f"Load Test Issue {random_string(subject_length)}"
        
        # Select random category
        category = random.choice(self.CATEGORIES)
        
        # Prepare form data
        form_data = {
            "name": name,
            "email": email,
            "subject": subject,
            "category": category,
            "message": self.LOAD_TEST_MESSAGE,
            "priority": random.choice(["low", "medium", "high"])
        }
        
        # Submit form
        with self.client.post(
            "/support/submit",
            json=form_data,
            catch_response=True,
            name="/support/submit"
        ) as response:
            # Check response
            if response.status_code == 200:
                # Validate response contains ticket_id
                try:
                    data = response.json()
                    if "ticket_id" in data:
                        response.success()
                    else:
                        response.failure("Missing ticket_id in response")
                except Exception as e:
                    response.failure(f"Invalid JSON response: {str(e)}")
            elif response.status_code == 422:
                # Validation errors are expected with random data
                response.success()
            else:
                response.failure(f"Unexpected status code: {response.status_code}")


